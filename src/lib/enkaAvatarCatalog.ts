export const ENKA_CHARACTER_ID_BY_AVATAR_ID = Object.fromEntries(
  Object.entries(ENKA_AVATAR_IDS_BY_CHARACTER_ID).flatMap(([characterId, avatarIds]) =>
    avatarIds.map((avatarId) => [avatarId, characterId]),
  ),
) as Record<number, CharacterPresetKey>;

export function resolveEnkaCharacterId(avatarId: number) {
  return ENKA_CHARACTER_ID_BY_AVATAR_ID[avatarId] ?? null;
}
